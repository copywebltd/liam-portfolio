"use client";

import { useEffect, useState } from "react";
import { adBreakdowns } from "@/data/hijacks";
import { Reveal, SectionHeading } from "./primitives";

/* ------------------------------------------------------------------ */
/*  BREAKDOWNS — our generated ads + the reasoning behind each one.    */
/*  Tap to read the thinking behind the copy and the design.           */
/* ------------------------------------------------------------------ */

export function Hijacks() {
  const [open, setOpen] = useState<string | null>(null);
  const active = adBreakdowns.find((a) => a.slug === open);

  useEffect(() => {
    const onKey = (e: KeyboardEvent) => {
      if (e.key === "Escape") setOpen(null);
    };
    window.addEventListener("keydown", onKey);
    document.body.style.overflow = open ? "hidden" : "";
    return () => {
      window.removeEventListener("keydown", onKey);
      document.body.style.overflow = "";
    };
  }, [open]);

  return (
    <section
      id="craft"
      className="relative py-28 md:py-36 border-t border-[var(--v4-border)]"
    >
      <div className="max-w-[1320px] mx-auto px-6 md:px-10">
        <SectionHeading
          index="01.8"
          eyebrow="The craft"
          title="The ads, and the"
          accent="thinking."
          description="Static ads my systems generated, composed around each brand's real product. Every one is a deliberate call — the angle, the psychology, the layout. Tap any ad to read the reasoning behind its copy and its design."
        />

        <div className="mt-14 grid grid-cols-2 lg:grid-cols-3 gap-4 md:gap-5">
          {adBreakdowns.map((a, i) => (
            <Reveal key={a.slug} delay={Math.min(i * 0.05, 0.3)}>
              <button
                onClick={() => setOpen(a.slug)}
                className="group block w-full text-left"
              >
                <div className="relative overflow-hidden rounded-xl border border-[var(--v4-border)] bg-[var(--v4-surface)]">
                  <img
                    src={`/showcase/hijack/${a.slug}-gen.jpg`}
                    alt={`${a.brand} ad, ${a.tag}`}
                    loading="lazy"
                    className="w-full aspect-square object-cover transition-transform duration-500 group-hover:scale-[1.03]"
                  />
                  <div className="absolute inset-0 bg-gradient-to-t from-black/60 to-transparent opacity-0 group-hover:opacity-100 transition-opacity duration-300" />
                  <div className="absolute bottom-3 left-3 right-3 flex items-center justify-between opacity-0 group-hover:opacity-100 transition-opacity duration-300">
                    <span className="text-[12.5px] font-medium text-white">
                      {a.brand}
                    </span>
                    <span className="font-mono text-[9.5px] uppercase tracking-[0.12em] text-[var(--v4-amber-hi)]">
                      read the thinking
                    </span>
                  </div>
                </div>
                <div className="mt-2.5 flex items-center justify-between gap-2">
                  <span className="text-[13px] font-medium text-[var(--v4-text)]">
                    {a.brand}
                  </span>
                  <span className="font-mono text-[10px] uppercase tracking-[0.12em] text-[var(--v4-text-3)]">
                    {a.tag}
                  </span>
                </div>
              </button>
            </Reveal>
          ))}
        </div>

        <Reveal delay={0.1}>
          <p className="mt-9 max-w-2xl font-mono text-[11.5px] leading-relaxed text-[var(--v4-text-3)]">
            Generated by my creative systems, not hand-designed. Every product is
            the brand&apos;s real packaging, accurate to the SKU — the system
            composes around it, never invents it.
          </p>
        </Reveal>
      </div>

      {/* lightbox — the ad + the thinking behind its copy and design */}
      {active && (
        <div
          className="fixed inset-0 z-[95] flex items-center justify-center p-4 md:p-8 bg-[rgba(6,5,4,0.9)] backdrop-blur-md"
          onClick={() => setOpen(null)}
          role="dialog"
          aria-modal="true"
          aria-label={`${active.brand} ad, the thinking`}
        >
          <button
            onClick={() => setOpen(null)}
            aria-label="Close"
            className="absolute top-5 right-5 grid place-items-center w-10 h-10 rounded-full border border-[var(--v4-border-strong)] bg-[rgba(10,9,7,0.6)] text-[var(--v4-text-2)] hover:text-[var(--v4-text)] hover:border-[rgba(245,158,11,0.5)] transition-colors z-10"
          >
            ✕
          </button>
          <div
            className="w-full max-w-[840px] grid md:grid-cols-[1fr_1fr] gap-5 md:gap-7 items-center"
            onClick={(e) => e.stopPropagation()}
          >
            <img
              src={`/showcase/hijack/${active.slug}-gen.jpg`}
              alt={`${active.brand} generated ad`}
              className="w-full h-auto max-h-[70vh] object-contain rounded-xl border border-[var(--v4-border-strong)]"
            />
            <div>
              <div className="font-mono text-[10px] uppercase tracking-[0.14em] text-[var(--v4-amber-hi)] mb-1">
                {active.tag}
              </div>
              <h3 className="text-[22px] font-semibold text-[var(--v4-text)] mb-5">
                {active.brand}
              </h3>
              <div className="mb-5">
                <div className="font-mono text-[10px] uppercase tracking-[0.14em] text-[var(--v4-text-3)] mb-1.5">
                  The copy
                </div>
                <p className="text-[14px] leading-relaxed text-[var(--v4-text-2)]">
                  {active.copy}
                </p>
              </div>
              <div>
                <div className="font-mono text-[10px] uppercase tracking-[0.14em] text-[var(--v4-text-3)] mb-1.5">
                  The design
                </div>
                <p className="text-[14px] leading-relaxed text-[var(--v4-text-2)]">
                  {active.design}
                </p>
              </div>
            </div>
          </div>
        </div>
      )}
    </section>
  );
}
