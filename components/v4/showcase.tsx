"use client";

import { useEffect, useState } from "react";
import { adShots } from "@/data/showcase";
import { Reveal, SectionHeading } from "./primitives";

/* ------------------------------------------------------------------ */
/*  SHOWCASE — the visual output the systems produce. Tap to enlarge.  */
/* ------------------------------------------------------------------ */

export function Showcase() {
  const [open, setOpen] = useState<string | null>(null);
  const active = adShots.find((a) => a.file === open);

  useEffect(() => {
    const onKey = (e: KeyboardEvent) => {
      if (e.key === "Escape") setOpen(null);
    };
    window.addEventListener("keydown", onKey);
    document.body.style.overflow = open ? "hidden" : "";
    return () => {
      window.removeEventListener("keydown", onKey);
      document.body.style.overflow = "";
    };
  }, [open]);

  return (
    <section
      id="showcase"
      className="relative py-28 md:py-36 border-t border-[var(--v4-border)]"
    >
      <div className="max-w-[1320px] mx-auto px-6 md:px-10">
        <SectionHeading
          index="01.75"
          eyebrow="The output"
          title="What the systems actually"
          accent="produce."
          description="Real static ads my systems generated, each routed through a different expert framework and composed around the brand's real product. Tap any one to enlarge."
        />

        <div className="mt-14 grid grid-cols-2 lg:grid-cols-3 gap-4 md:gap-5">
          {adShots.map((a, i) => (
            <Reveal key={a.file} delay={Math.min(i * 0.05, 0.3)}>
              <button
                onClick={() => setOpen(a.file)}
                className="group block w-full text-left"
              >
                <div className="relative overflow-hidden rounded-xl border border-[var(--v4-border)] bg-[var(--v4-surface)]">
                  <img
                    src={`/showcase/${a.file}`}
                    alt={`${a.brand} ad, ${a.tag}`}
                    loading="lazy"
                    className="w-full aspect-square object-cover transition-transform duration-500 group-hover:scale-[1.03]"
                  />
                  <div className="absolute inset-0 bg-gradient-to-t from-black/55 to-transparent opacity-0 group-hover:opacity-100 transition-opacity duration-300" />
                  <div className="absolute bottom-3 left-3 right-3 flex items-center justify-between opacity-0 group-hover:opacity-100 transition-opacity duration-300">
                    <span className="text-[12.5px] font-medium text-white">
                      {a.brand}
                    </span>
                    <span className="font-mono text-[9.5px] uppercase tracking-[0.12em] text-[var(--v4-amber-hi)]">
                      enlarge
                    </span>
                  </div>
                </div>
                <div className="mt-2.5 flex items-center justify-between gap-2">
                  <span className="text-[13px] font-medium text-[var(--v4-text)]">
                    {a.brand}
                  </span>
                  <span className="font-mono text-[10px] uppercase tracking-[0.12em] text-[var(--v4-text-3)]">
                    {a.tag}
                  </span>
                </div>
              </button>
            </Reveal>
          ))}
        </div>

        <Reveal delay={0.1}>
          <p className="mt-9 max-w-2xl font-mono text-[11.5px] leading-relaxed text-[var(--v4-text-3)]">
            Generated by my creative systems, not hand-designed. Every product is
            composed around the brand&apos;s real packaging, accurate to the SKU.
          </p>
        </Reveal>
      </div>

      {/* lightbox (state-driven, no exit animation) */}
      {active && (
        <div
          className="fixed inset-0 z-[95] flex items-center justify-center p-4 md:p-8 bg-[rgba(6,5,4,0.88)] backdrop-blur-md"
          onClick={() => setOpen(null)}
          role="dialog"
          aria-modal="true"
          aria-label={`${active.brand} ad`}
        >
          <button
            onClick={() => setOpen(null)}
            aria-label="Close"
            className="absolute top-5 right-5 grid place-items-center w-10 h-10 rounded-full border border-[var(--v4-border-strong)] bg-[rgba(10,9,7,0.6)] text-[var(--v4-text-2)] hover:text-[var(--v4-text)] hover:border-[rgba(245,158,11,0.5)] transition-colors"
          >
            ✕
          </button>
          <figure
            className="max-w-[92vw] md:max-w-[620px]"
            onClick={(e) => e.stopPropagation()}
          >
            <img
              src={`/showcase/${active.file}`}
              alt={`${active.brand} ad, ${active.tag}`}
              className="w-full h-auto max-h-[80vh] object-contain rounded-xl border border-[var(--v4-border-strong)]"
            />
            <figcaption className="mt-3 flex items-center justify-between v4-mono-dim">
              <span className="text-[var(--v4-text-2)]">{active.brand}</span>
              <span>{active.tag}</span>
            </figcaption>
          </figure>
        </div>
      )}
    </section>
  );
}
